let pass = 0, fail = 0;
function sum(r) {
  return r.actions.map(a => {
    if (a.op === 'add') {
      const f = a.f, k = [f.type];
      if (f.total) k.push('total');
      if (f.start != null && !f.total) k.push(`${f.start}-${f.end}`);
      if (f.hour != null) k.push('@' + f.hour);
      if (f.hours) k.push('@' + f.hours.join(','));
      if (f.depth && f.depth !== 'normal') k.push(f.depth);
      if (f.extent) k.push('ext:' + f.extent);
      if (f.size) k.push('size' + f.size);
      if (f.radial) k.push('r:' + f.radial);
      if (f.encircling) k.push('enc');
      if (f.grade) k.push('g' + f.grade + (f.loc || ''));
      if (f.around) k.push('around');
      if (f.chronic) k.push('chronic');
      if (f.pigmented) k.push('pig');
      if (f.holes) k.push('holes');
      return k.join(' ');
    }
    if (a.op === 'status') return `status ${a.macula}/${a.fovea}`;
    if (a.op === 'eye') return 'eye ' + a.eye;
    if (a.op === 'lincoff') return 'lincoff ' + a.on;
    if (a.op === 'remove') return 'remove ' + (a.last ? 'last' : a.type + (a.hour ? '@' + a.hour : ''));
    if (a.op === 'move') return `move ${a.type}${a.from ? '@' + a.from : ''}->${a.to}`;
    if (a.op === 'extend') return 'extend ' + a.to;
    if (a.op === 'rdmod') return 'rdmod ' + Object.entries(a).filter(([k]) => k !== 'op').map(([k, v]) => k + '=' + v).join(',');
    return a.op;
  }).join(' | ');
}
function t(input, expected, ctx) {
  const r = RD.parse(input, ctx || { eye: 'OS' });
  const got = sum(r);
  if (got === expected) pass++;
  else { fail++; console.log(`✗ ${JSON.stringify(input)}\n   expected: ${expected}\n   got:      ${got}\n   norm:     ${r.norm}${r.unknown.length ? '\n   unknown:  ' + r.unknown.join(',') : ''}`); }
}

