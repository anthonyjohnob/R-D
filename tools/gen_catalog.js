/* Generate src/catalog.js from research/catalog.json.
   For entries that the original engine already draws (tears, lattice, RD, buckles…), keep only the
   phrases the original parser does NOT already understand as that finding, so its finer handling
   (plurals, counts, ranges) still applies; phrases that carry extra meaning (exudative, fresh blood,
   suprachoroidal haemorrhage…) are always kept. Prints phrases that the old parser would have read
   as something else, for review. */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const RD = require(path.join(root, 'src', 'core.js'));
const cat = JSON.parse(fs.readFileSync(path.join(root, 'research', 'catalog.json'), 'utf8'));

const PROBE = { rd: ' from 10 to 2', grt: ' from 10 to 2', dia: ' from 4 to 6', lat: ' from 7 to 8', chd: ' from 4 to 8', buckle: ' from 10 to 2', laser: ' at 12', cryo: ' at 12', vh: ' at 6' };
const legacyTypes = (phrase, type) => {
  const p = RD.parse(phrase + (PROBE[type] || ' at 12'), { eye: 'OS', noCatalog: true });
  return p.actions.map(a => a.op === 'add' ? a.f.type : a.op === 'rdmod' ? (a.chronic ? 'dem' : a.rolled ? 'rolled' : 'rdmod') : a.op);
};
// entries that add meaning to an engine finding keep a phrase only if it carries that meaning
const KEEP_IF = {
  encircling_scleral_buckle: /encircl|360|cerclage|circlage|band/, lattice_with_atrophic_holes: /hole/, lattice_with_tractional_tear: /tear/,
  pigmented_lattice: /pigment/, subclinical_retinal_detachment: /subclinical|asymptomatic/, exudative_retinal_detachment: /exudat|serous|rhegmat|erd|srd/,
  combined_tractional_rhegmatogenous_rd: /combined|trd|tractional/, schisis_detachment: /schisis|olb|outer layer/,
  suprachoroidal_hemorrhage: /hem|haem|bleed|expulsive|sch/, kissing_choroidal_detachment: /kiss|apposi/, red_blood_in_vitreous: /fresh|red|clot/,
  laser_360: /360|three sixty|circumferential/, anterior_pvr: /anterior|apvr|circumferential|loop|base|perpendicular|trough/,
};
const conflicts = [];
for (const e of cat) {
  if (e.map) {
    const extra = Object.keys(e.map).filter(k => k !== 'type').length > 0;
    const want = e.map.type === 'star' ? 'pvr' : e.map.type === 'lattear' ? 'lattear-never' : e.map.type;
    if (e.map.type === 'auto') { e.match = []; continue; }
    e.match = e.match.filter(ph => !legacyTypes(ph, want).includes(want) || (extra && KEEP_IF[e.id] && KEEP_IF[e.id].test(ph)));
  } else {
    for (const ph of e.match) {
      const t = legacyTypes(ph, 'x').filter(x => x !== 'lincoff');
      if (t.length) conflicts.push(`${ph} → was ${t.join('+')}, now ${e.id}`);
    }
  }
}
const slim = cat.map(e => {
  const o = { ...e };
  for (const k of Object.keys(o)) if (o[k] == null || o[k] === '' || (Array.isArray(o[k]) && !o[k].length && k !== 'match')) delete o[k];
  return o;
});
const js = '/* R/D pathology catalogue — generated by tools/gen_catalog.js from research/catalog.json.\n' +
  '   Each entry: colour code (fill/outline/pattern), definition, drawing notes and PubMed references. */\n' +
  '(function (root) {\nconst CATALOG = ' + JSON.stringify(slim) + ';\n' +
  "if (typeof module !== 'undefined' && module.exports) module.exports = CATALOG; else root.RD_CATALOG = CATALOG;\n" +
  "})(typeof window !== 'undefined' ? window : globalThis);\n";
fs.writeFileSync(path.join(root, 'src', 'catalog.js'), js);
console.log(`catalog.js: ${slim.length} entries, ${(js.length / 1024).toFixed(0)} KB, ${slim.reduce((n, e) => n + e.match.length, 0)} phrases`);
console.log('mapped entries keep:', cat.filter(e => e.map).map(e => `${e.id}[${e.match.join('|')}]`).join('\n  '));
console.log(`\n${conflicts.length} phrases the old parser read differently:\n  ` + conflicts.join('\n  '));
